use std::time::Duration;

use crate::starboard;

#[must_use]
pub fn bench_markdown(
    reports: &[starboard::bench::BenchReport],
    machine: &starboard::bench::MachineInfo,
    date: &str,
    repaint: &[starboard::bench::RepaintCost],
) -> String {
    let mut out = String::new();
    out.push_str("# Starboard benchmark\n\n");
    out.push_str("Generated by `just bench-starboard` — do not edit by hand.\n\n");
    out.push_str(&format!("- Date: {date}\n"));
    out.push_str(&format!(
        "- Machine: {} · {} · {} threads\n",
        machine.kernel, machine.cpu, machine.cores
    ));
    out.push_str(&format!(
        "- Profile: dev (crate `opt-level = 0`, dependencies `1`) · {} s warm-up excluded\n",
        starboard::bench::BENCH_WARMUP_SECONDS
    ));
    out.push_str(&format!(
        "- Brush: size index {} (radius {}), one stroke per frame at {} ops/s per peer\n",
        starboard::bench::BENCH_SIZE_INDEX,
        starboard::canvas::brush_radius(starboard::bench::BENCH_SIZE_INDEX),
        starboard::bench::BENCH_OPS_PER_SECOND
    ));
    out.push_str(
        "- In-process peers on localhost, full mesh, direct dial — no Freenet discovery, no NAT/relay (§0.8)\n\n",
    );
    out.push_str("| Peers | Achieved ops/s per peer | Op latency p50 | p99 | Received bytes/s per peer | Dropped before repair | Convergence | Anti-entropy announcement |\n");
    out.push_str("|---:|---:|---:|---:|---:|---:|---:|---:|\n");
    for report in reports {
        out.push_str(&format!(
            "| {} | {:.1} | {} | {} | {:.1} KiB | {:.1} % | {} | {} |\n",
            report.config.peers,
            report.achieved_ops_per_second,
            format_duration(report.latency.p50),
            format_duration(report.latency.p99),
            report.received_bytes_per_second / 1024.0,
            report.dropped_percent,
            format_duration(report.convergence),
            format_bytes(u64::try_from(report.announcement_bytes).unwrap_or(0)),
        ));
    }
    out.push_str("\n## Inbound bytes per peer\n\n| Peers | Peer | Received |\n|---:|---|---:|\n");
    for report in reports {
        for traffic in &report.per_peer_bytes {
            out.push_str(&format!(
                "| {} | {} | {} |\n",
                report.config.peers,
                traffic.peer.as_str(),
                format_bytes(traffic.received_bytes)
            ));
        }
    }
    out.push_str("\n## CPU tile repaint (headless)\n\n");
    out.push_str("One `repaint_dirty_tiles` pass over a fully painted 4 MiB canvas:\n\n");
    out.push_str("| Dirty tiles | Repaint |\n|---:|---:|\n");
    for cost in repaint {
        out.push_str(&format!(
            "| {} | {} |\n",
            cost.dirty_tiles,
            format_duration(Duration::from_micros(cost.micros))
        ));
    }
    out.push_str("\n## Limits of this measurement\n\n");
    out.push_str("- Op latency runs from writing the op into the app to the receiver's inbound event\n  (the gossip payload carrying that op). The op crosses several unordered `Update` hops\n  — the input message → `write_ops` → `poll_p2p_events` on the sender, then\n  `poll_p2p_events` → `drive` on the receiver — and each hop can cost a frame, so at\n  60 Hz the ~50 ms p50 is a scheduling floor, not a transport number.\n");
    out.push_str(
        "- `Achieved ops/s per peer` below 60 means the process could not hold the cadence; the\n  latency in that row then measures queueing on top of that frame floor.\n- The sender's own local apply and the rasterize/merge CPU cost are not part of it.\n",
    );
    out.push_str("- Byte counts are gossipsub payloads (ops, anti-entropy announcements and repair\n  frames). Transport framing, gossipsub metadata and identify/kad/ping are excluded.\n");
    out.push_str("- The anti-entropy announcement is 12 bytes per touched tile, so it grows with the\n  painted area rather than with the canvas (1024 tiles fully painted would be ~12 KiB).\n");
    out.push_str("- Dropped means \"never arrived as a gossip op\": repair delivers a slice instead, so\n  a dropped op still converges.\n");
    out.push_str("- The tap drains every ~1 ms; the `NetEventChannel` holds 1024 events, so a lagging\n  tap would inflate the dropped rate.\n");
    out.push_str("- The 4 MiB GPU texture re-upload while painting (B4's open issue) needs a render\n  world; headless only the CPU repaint above is measurable.\n");
    out
}

// needed helper: a duration in the unit that keeps one decimal (µs below 1 ms)
fn format_duration(duration: Duration) -> String {
    let micros = u64::try_from(duration.as_micros()).unwrap_or(u64::MAX);
    if micros < 1000 {
        return format!("{micros} µs");
    }
    let whole = micros / 1000;
    let tenth = micros.saturating_sub(whole.saturating_mul(1000)) / 100;
    format!("{whole}.{tenth} ms")
}

// needed helper: a byte count as KiB with one decimal
fn format_bytes(bytes: u64) -> String {
    let whole = bytes / 1024;
    let tenth = bytes
        .saturating_sub(whole.saturating_mul(1024))
        .saturating_mul(10)
        / 1024;
    format!("{whole}.{tenth} KiB")
}

#[cfg(test)]
mod tests {
    use std::time::Duration;

    use freenet_libp2p_bevy_plugin::identity;

    use super::bench_markdown;
    use crate::starboard;

    #[test]
    fn test_usage() {
        let report = starboard::bench::BenchReport {
            config: starboard::bench::ScenarioConfig {
                peers: 8,
                ops_per_second: 60,
                seconds: 20,
            },
            achieved_ops_per_second: 59.5,
            latency: starboard::bench::LatencyPercentiles {
                p50: Duration::from_micros(1500),
                p99: Duration::from_micros(12_340),
                samples: 1000,
            },
            received_bytes_per_second: 153_600.0,
            dropped_percent: 0.4,
            convergence: Duration::from_millis(900),
            announcement_bytes: 12_288,
            per_peer_bytes: vec![starboard::bench::PeerTraffic {
                peer: identity::PeerId::from("peer-a"),
                received_bytes: 2048,
            }],
        };
        let machine = starboard::bench::MachineInfo {
            kernel: String::from("Linux test"),
            cpu: String::from("Test CPU"),
            cores: 6,
        };
        let repaint = [
            starboard::bench::RepaintCost {
                dirty_tiles: 1,
                micros: 900,
            },
            starboard::bench::RepaintCost {
                dirty_tiles: 32,
                micros: 1234,
            },
        ];

        let markdown = bench_markdown(&[report], &machine, "2026-01-01T00:00:00Z", &repaint);

        assert!(markdown.starts_with("# Starboard benchmark"));
        assert!(markdown.contains("- Date: 2026-01-01T00:00:00Z"));
        assert!(markdown.contains("Linux test · Test CPU · 6 threads"));
        assert!(
            markdown.contains(
                "| 8 | 59.5 | 1.5 ms | 12.3 ms | 150.0 KiB | 0.4 % | 900.0 ms | 12.0 KiB |"
            )
        );
        assert!(markdown.contains("| 8 | peer-a | 2.0 KiB |"));
        assert!(markdown.contains("| 1 | 900 µs |"));
        assert!(markdown.contains("| 32 | 1.2 ms |"));
        assert!(markdown.contains("## Limits of this measurement"));
    }
}
